"""Four independently authorized Python handlers and immutable published versions."""

from __future__ import annotations

from pathlib import Path

from aws_cdk import Duration, RemovalPolicy
from aws_cdk import aws_iam as iam
from aws_cdk import aws_lambda as lambda_
from aws_cdk import aws_logs as logs
from constructs import Construct

from infra.assets import validate_lambda_asset
from semantic_service.route_budget import FACADE_TIMEOUT_SECONDS, FALLBACK_TIMEOUT_SECONDS


class Functions(Construct):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        prefix: str,
        asset_path: Path,
        environments: dict[str, dict[str, str]],
        permissions: dict[str, list[iam.PolicyStatement]],
        request_asset_path: Path | None = None,
        request_provisioned_concurrency: int = 0,
        retention_days: int = 30,
        ecs_enabled: bool = False,
        ecs_asset_path: Path | None = None,
        facade_vpc_config: lambda_.CfnFunction.VpcConfigProperty | None = None,
    ) -> None:
        super().__init__(scope, construct_id)
        asset_path = validate_lambda_asset(asset_path, "shared")
        if ecs_enabled != (ecs_asset_path is not None):
            raise ValueError("ecs_asset_path must be supplied exactly when ECS Search is enabled")
        if ecs_asset_path is not None:
            ecs_asset_path = validate_lambda_asset(ecs_asset_path, "ecs")
        if request_asset_path is not None:
            request_asset_path = validate_lambda_asset(request_asset_path, "request")
        if (
            type(request_provisioned_concurrency) is not int
            or request_provisioned_concurrency < 0
            or (request_provisioned_concurrency and request_asset_path is None)
        ):
            raise ValueError(
                "REQUEST provisioned concurrency requires a REQUEST ZIP and count >= 0"
            )
        self.aliases: dict[str, lambda_.Alias] = {}
        self.log_groups: dict[str, logs.LogGroup] = {}
        self.names: dict[str, str] = {}
        retention = {
            7: logs.RetentionDays.ONE_WEEK,
            14: logs.RetentionDays.TWO_WEEKS,
            30: logs.RetentionDays.ONE_MONTH,
            60: logs.RetentionDays.TWO_MONTHS,
            90: logs.RetentionDays.THREE_MONTHS,
            180: logs.RetentionDays.SIX_MONTHS,
            365: logs.RetentionDays.ONE_YEAR,
        }[retention_days]
        profiles = [
            ("search", 2048, 10),
            # 1769 MB ≈ 1 vCPU；冷 factory 2213→341 ms，见 docs/capacity.md#request-默认尺寸与回滚。
            ("request", 1769, 10),
            ("indexer", 1024, 45),
            ("enhancer", 1024, 240),
        ]
        if ecs_enabled:
            profiles.extend(
                (
                    ("facade", 512, FACADE_TIMEOUT_SECONDS),
                    ("fallback", 2048, FALLBACK_TIMEOUT_SECONDS),
                )
            )
        for operation, memory, timeout in profiles:
            name = f"{prefix}-{operation}"
            request_package = operation == "request" and request_asset_path is not None
            operation_asset = request_asset_path if request_package else asset_path
            if operation in ("facade", "fallback"):
                operation_asset = ecs_asset_path
            handler_module = "request_runtime" if request_package else "runtime"
            handler = f"semantic_service.{handler_module}.{operation}_handler"
            if operation == "fallback":
                handler = "semantic_service.fallback.handler"
            elif operation == "facade":
                handler = "semantic_service.facade_lambda.handler"
            group = logs.LogGroup(
                self,
                f"{operation}Logs",
                log_group_name=f"{name}-logs",
                retention=retention,
                removal_policy=RemovalPolicy.RETAIN,
            )
            role = iam.Role(
                self,
                f"{operation}Role",
                role_name=f"{name}-role",
                assumed_by=iam.ServicePrincipal("lambda.amazonaws.com"),
                inline_policies={
                    f"{name}-runtime": iam.PolicyDocument(
                        statements=[
                            *permissions[operation],
                            iam.PolicyStatement(
                                actions=["logs:CreateLogStream", "logs:PutLogEvents"],
                                # LogGroup Arn includes the required trailing stream
                                # wildcard. Stream IDs are generated by the runtime.
                                resources=[group.log_group_arn],
                            ),
                        ]
                    ),
                },
            )
            function = lambda_.Function(
                self,
                f"{operation}Function",
                function_name=name,
                runtime=lambda_.Runtime.PYTHON_3_12,
                architecture=lambda_.Architecture.X86_64,
                handler=handler,
                code=lambda_.Code.from_asset(str(operation_asset)),
                role=role,
                environment=environments[operation],
                memory_size=memory,
                timeout=Duration.seconds(timeout),
                reserved_concurrent_executions=1 if operation in ("indexer", "enhancer") else None,
                log_group=group,
                current_version_options=lambda_.VersionOptions(removal_policy=RemovalPolicy.RETAIN),
            )
            if operation == "facade" and facade_vpc_config is not None:
                # Apply before current_version is computed. CDK includes VpcConfig
                # in its version hash; explicit IAM below avoids a managed policy.
                cfn_function = function.node.default_child
                assert isinstance(cfn_function, lambda_.CfnFunction)
                cfn_function.vpc_config = facade_vpc_config
            self.aliases[operation] = lambda_.Alias(
                self,
                f"{operation}Alias",
                alias_name="live",
                version=function.current_version,
                provisioned_concurrent_executions=(
                    request_provisioned_concurrency
                    if operation == "request" and request_provisioned_concurrency
                    else None
                ),
            )
            self.log_groups[operation] = group
            self.names[operation] = name
